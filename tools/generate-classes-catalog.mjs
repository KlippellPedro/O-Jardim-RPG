import fs from 'node:fs';

const catalogPath = new URL('../data/ficha/classes.json', import.meta.url);
const currentCatalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));

const slug = value => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/(^-|-$)/g, '');

const power = ([titulo, custo_mana, descricao, pre_requisitos]) => ({
  id: slug(titulo),
  titulo,
  custo_mana,
  descricao,
  ...(pre_requisitos ? { pre_requisitos: Array.isArray(pre_requisitos) ? pre_requisitos : [pre_requisitos] } : {}),
});

const progression = ({ titulo, core, secondary, feature, featureLevel = 18, event }) => {
  const rewards = {
    1: [{ tipo: 'habilidade', titulo: core.titulo, estagio: 1 }, { tipo: 'grau_pericia', titulo: 'Grau de perícia' }],
    2: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }],
    3: [{ tipo: 'habilidade', titulo: secondary.titulo, estagio: 1 }],
    4: [{ tipo: 'evento', titulo: event.titulo }],
    5: [{ tipo: 'habilidade', titulo: core.titulo, estagio: 2 }],
    6: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }, { tipo: 'grau_pericia', titulo: 'Grau de perícia' }],
    7: [{ tipo: 'evento', titulo: event.titulo }],
    8: [{ tipo: 'habilidade', titulo: secondary.titulo, estagio: 2 }],
    9: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }],
    10: [{ tipo: 'habilidade', titulo: core.titulo, estagio: 3 }],
    11: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }, { tipo: 'grau_pericia', titulo: 'Grau de perícia' }],
    12: [{ tipo: 'evento', titulo: event.titulo }],
    13: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }],
    14: [{ tipo: 'habilidade', titulo: secondary.titulo, estagio: 3 }],
    15: [{ tipo: 'habilidade', titulo: core.titulo, estagio: 4 }],
    16: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }],
    17: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }, { tipo: 'grau_pericia', titulo: 'Grau de perícia' }],
    18: [{ tipo: 'evento', titulo: event.titulo }],
    19: [{ tipo: 'poder', titulo: `Poder de ${titulo}` }],
    20: [
      { tipo: 'habilidade', titulo: core.titulo, estagio: 5 },
      { tipo: 'habilidade', titulo: secondary.titulo, estagio: 4 },
      { tipo: 'habilidade_final', titulo: core.final || 'Habilidade Final' },
    ],
  };
  rewards[featureLevel].push({ tipo: 'habilidade', titulo: feature.titulo });
  return Array.from({ length: 20 }, (_, index) => ({ nivel: index + 1, recompensas: rewards[index + 1] }));
};

const makeClass = definition => {
  const {
    id, titulo, vida, mana, descricao, core, secondary, feature, featureLevel, event, powers,
    arvore = null, arvores, disponibilidade = 'geral', categoria = 'padrao', origem = 'proposta_original_balanceada',
    nome_provisorio = false,
  } = definition;
  const isSpecial = categoria === 'esquecida';
  const allowedTrees = arvores || (arvore ? [arvore] : []);

  const classProgression = progression({ titulo, core, secondary, feature, featureLevel, event });
  if (isSpecial) {
    classProgression.forEach(level => level.recompensas.forEach(reward => {
      if (reward.tipo === 'grau_pericia') reward.quantidade = 2;
    }));
  }

  return {
    id,
    tipo: 'classe',
    titulo,
    categoria,
    disponibilidade: isSpecial ? 'restrita' : disponibilidade,
    arvore,
    ...(isSpecial ? { arvores: allowedTrees, patamar: 'conquista', requer_autorizacao_mestre: true } : {}),
    vida,
    mana,
    recursos_provisorios: false,
    progressao_publicada: true,
    origem_conteudo: origem,
    versao_balanceamento: '2026-07-28',
    ...(nome_provisorio ? { nome_provisorio: true } : {}),
    descricao,
    progressao: classProgression,
    habilidades: [
      {
        id: slug(core.titulo),
        titulo: core.titulo,
        niveis: [1, 5, 10, 15, 20],
        estagios: core.stages.map((descricaoEstagio, index) => ({
          nivel: [1, 5, 10, 15, 20][index],
          descricao: descricaoEstagio,
        })),
      },
      { id: slug(secondary.titulo), titulo: secondary.titulo, descricao: secondary.descricao, niveis: [3, 8, 14, 20] },
      { id: slug(feature.titulo), titulo: feature.titulo, descricao: feature.descricao, niveis: [featureLevel || 18] },
    ],
    eventos: [{ id: slug(event.titulo), titulo: event.titulo, descricao: event.descricao, niveis: [4, 7, 12, 18] }],
    poderes: powers.map(power),
  };
};

